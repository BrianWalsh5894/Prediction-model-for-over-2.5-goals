"""
Phase 6 - Exploratory Analysis.

Reads data/clean/matches_clean.csv (+ data/clean/features.csv for the
feature-correlation section) and writes:
  - reports/phase6_eda.md       (all tables + findings, in writing)
  - reports/figures/*.png       (the plots referenced from that report)

Nothing here touches the model - it's pure description of the data,
so there's no leakage concern. Safe to re-run any time the clean
dataset changes.

Run from inside src/:
    python eda.py
"""

import os
import pandas as pd
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

CLEAN_CSV = os.path.join("..", "data", "clean", "matches_clean.csv")
FEATURES_CSV = os.path.join("..", "data", "clean", "features.csv")
REPORT_MD = os.path.join("..", "reports", "phase6_eda.md")
FIG_DIR = os.path.join("..", "reports", "figures")

# The current, in-progress season - excluded from season-level stats so a
# half-finished campaign doesn't distort an "average" or "rate" figure.
LIVE_SEASON = "2026/27"

REDUNDANCY_THRESHOLD = 0.9  # |corr| between two features above this = treat as redundant


def md_table(df, float_fmt="{:.3f}"):
    """Plain markdown table, written by hand so this doesn't depend on the
    optional `tabulate` package (df.to_markdown() needs it and it may not
    be in the over25 env)."""
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: float_fmt.format(v) if pd.notna(v) else "")
        else:
            df[c] = df[c].astype(str)

    header = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|"
    rows = ["| " + " | ".join(row) + " |" for row in df.itertuples(index=False, name=None)]
    return "\n".join([header, sep] + rows)


def main():
    df = pd.read_csv(CLEAN_CSV, parse_dates=["match_date"])
    complete = df[df["season"] != LIVE_SEASON].copy()  # for rate/average tables only

    os.makedirs(FIG_DIR, exist_ok=True)
    lines = []
    lines.append("# Phase 6 - Exploratory Analysis\n")
    lines.append(f"Generated by `src/eda.py` from `data/clean/matches_clean.csv` "
                  f"({len(df)} matches total, {len(complete)} excluding the in-progress "
                  f"{LIVE_SEASON} season).\n")

    # --- 1. Overall Over 2.5 % -------------------------------------------
    overall_rate = complete["over_2_5"].mean()
    lines.append("## 1. Overall Over 2.5 %\n")
    lines.append(f"**{overall_rate:.1%}** of completed matches finish Over 2.5 goals "
                  f"({complete['over_2_5'].sum():,} of {len(complete):,}).\n")

    # --- 2. Over 2.5 % by league and season ------------------------------
    by_league_season = (
        complete.groupby(["league_name", "season"])["over_2_5"]
        .agg(["mean", "count"])
        .rename(columns={"mean": "over_2_5_rate", "count": "n_matches"})
        .reset_index()
        .sort_values(["league_name", "season"])
    )
    by_league = (
        complete.groupby("league_name")["over_2_5"]
        .agg(["mean", "count"])
        .rename(columns={"mean": "over_2_5_rate", "count": "n_matches"})
        .reset_index()
        .sort_values("over_2_5_rate", ascending=False)
    )
    lines.append("## 2. Over 2.5 % by league and by season\n")
    lines.append("### By league (all completed seasons)\n")
    lines.append(md_table(by_league) + "\n")
    lines.append("### By league and season\n")
    lines.append(md_table(by_league_season) + "\n")

    fig, ax = plt.subplots(figsize=(10, 5))
    for league in by_league_season["league_name"].unique():
        sub = by_league_season[by_league_season["league_name"] == league]
        ax.plot(sub["season"], sub["over_2_5_rate"], marker="o", label=league)
    ax.set_ylabel("Over 2.5 rate")
    ax.set_xlabel("Season")
    ax.set_title("Over 2.5 % by league and season")
    ax.legend()
    ax.tick_params(axis="x", rotation=45)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG_DIR, "over25_by_league_season.png"), dpi=120)
    plt.close(fig)
    lines.append("![Over 2.5 % by league and season](figures/over25_by_league_season.png)\n")

    # --- 3. Average goals (total, home, away) by league -----------------
    goals_by_league = (
        complete.groupby("league_name")[["total_goals", "home_goals", "away_goals"]]
        .mean()
        .rename(columns={"total_goals": "avg_total_goals", "home_goals": "avg_home_goals", "away_goals": "avg_away_goals"})
        .reset_index()
        .sort_values("avg_total_goals", ascending=False)
    )
    lines.append("## 3. Average goals (total, home, away) by league\n")
    lines.append(md_table(goals_by_league) + "\n")

    # --- 4. Shots vs goals relationship ----------------------------------
    team_shots_goals = pd.concat([
        complete[["home_shots", "home_goals"]].rename(columns={"home_shots": "shots", "home_goals": "goals"}),
        complete[["away_shots", "away_goals"]].rename(columns={"away_shots": "shots", "away_goals": "goals"}),
    ]).dropna()
    shots_goals_corr = team_shots_goals["shots"].corr(team_shots_goals["goals"])

    team_sot_goals = pd.concat([
        complete[["home_shots_on_target", "home_goals"]].rename(columns={"home_shots_on_target": "sot", "home_goals": "goals"}),
        complete[["away_shots_on_target", "away_goals"]].rename(columns={"away_shots_on_target": "sot", "away_goals": "goals"}),
    ]).dropna()
    sot_goals_corr = team_sot_goals["sot"].corr(team_sot_goals["goals"])

    lines.append("## 4. Shots vs goals relationship\n")
    lines.append(f"Per team-performance (one row per team per match), correlation of "
                  f"shots with goals scored: **{shots_goals_corr:.3f}**. Shots on target "
                  f"with goals scored: **{sot_goals_corr:.3f}** (expected to be higher - "
                  f"shots on target is a much more direct precursor to a goal than "
                  f"total shots).\n")

    binned = team_shots_goals.copy()
    binned["shots_bucket"] = pd.cut(binned["shots"], bins=range(0, 36, 3))
    bucket_means = binned.groupby("shots_bucket", observed=True)["goals"].mean()

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(bucket_means.index.astype(str), bucket_means.values, marker="o")
    ax.set_xlabel("Shots (bucketed)")
    ax.set_ylabel("Average goals scored")
    ax.set_title("Shots vs goals scored (team-level, per match)")
    ax.tick_params(axis="x", rotation=60)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG_DIR, "shots_vs_goals.png"), dpi=120)
    plt.close(fig)
    lines.append("![Shots vs goals](figures/shots_vs_goals.png)\n")

    # --- 5. Feature correlations and weak/redundant features ------------
    feats = pd.read_csv(FEATURES_CSV, parse_dates=["match_date"])
    numeric = feats.select_dtypes(include=[np.number]).drop(columns=["over_2_5"], errors="ignore")
    numeric = numeric.loc[:, numeric.std() > 0]  # drop constant columns, undefined correlation

    target_corr = feats[numeric.columns].corrwith(feats["over_2_5"]).dropna().sort_values(key=abs, ascending=True)
    weak = target_corr[target_corr.abs() < 0.03]

    lines.append("## 5. Feature correlations and weak/redundant features\n")
    lines.append(f"{len(weak)} of {len(target_corr)} numeric features correlate with "
                  f"`over_2_5` at `|corr| < 0.03` (essentially no linear signal on their "
                  f"own - doesn't rule out they help in combination, but worth knowing):\n")
    lines.append(md_table(weak.reset_index().rename(columns={"index": "feature", 0: "corr"})) + "\n")

    corr_matrix = numeric.corr()
    pairs = []
    cols = corr_matrix.columns
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            v = corr_matrix.iloc[i, j]
            if pd.notna(v) and abs(v) > REDUNDANCY_THRESHOLD:
                pairs.append((cols[i], cols[j], v))
    pairs.sort(key=lambda p: -abs(p[2]))

    lines.append(f"\n{len(pairs)} feature pairs correlate with each other at "
                  f"`|corr| > {REDUNDANCY_THRESHOLD}` (redundant - carrying both adds "
                  f"little and just inflates the feature count):\n")
    if pairs:
        pairs_df = pd.DataFrame(pairs, columns=["feature_a", "feature_b", "corr"]).head(30)
        lines.append(md_table(pairs_df) + "\n")
        if len(pairs) > 30:
            lines.append(f"(showing top 30 of {len(pairs)})\n")

    # --- 6. Unusual patterns: COVID seasons, early-season effects -------
    lines.append("## 6. Unusual patterns\n")
    lines.append("### COVID-affected seasons\n")
    covid_check = (
        df.groupby("season")[["total_goals"]]
        .mean()
        .join(df.groupby("season").apply(lambda g: (g["result"] == "H").mean(), include_groups=False).rename("home_win_rate"))
        .loc[["2018/19", "2019/20", "2020/21", "2021/22"]]
    )
    lines.append(md_table(covid_check.reset_index()) + "\n")
    lines.append("Matches the finding already in `data_dictionary.md`: 2020/21 "
                  "(fully behind closed doors) is a clear outlier on both goals and "
                  "home win rate; 2019/20 (partial) barely moves; 2021/22 snaps back "
                  "to normal. Confirms `behind_closed_doors` is the right place for "
                  "this, not a reason to drop or adjust those seasons further.\n")

    lines.append("### Early-season effect\n")
    feats_complete = feats[feats["season"] != LIVE_SEASON]
    early_bucket = np.minimum(feats_complete[["home_season_match_num", "away_season_match_num"]].min(axis=1), 10)
    early_df = pd.DataFrame({"min_season_games_played": early_bucket, "over_2_5": feats_complete["over_2_5"]})
    early_rate = early_df.groupby("min_season_games_played")["over_2_5"].agg(["mean", "count"])
    lines.append(md_table(early_rate.reset_index().rename(columns={"mean": "over_2_5_rate", "count": "n_matches"})) + "\n")
    lines.append("`min_season_games_played` is capped at 10 (games 10+ grouped together) "
                  "for readability. Any step change in the early rows versus the rest "
                  "would suggest an early-season effect worth a dedicated feature; a flat "
                  "line says the blended/rolling features already handle it adequately.\n")

    # --- 7. Market calibration -------------------------------------------
    lines.append("## 7. Market calibration (de-margined odds vs actual Over rate)\n")
    market = complete.dropna(subset=["avg_over_2_5", "avg_under_2_5"]).copy()
    market["implied_over"] = (1 / market["avg_over_2_5"])
    market["implied_under"] = (1 / market["avg_under_2_5"])
    market["market_prob_over"] = market["implied_over"] / (market["implied_over"] + market["implied_under"])

    market["prob_bucket"] = pd.cut(market["market_prob_over"], bins=np.arange(0, 1.05, 0.05))
    calib = (
        market.groupby("prob_bucket", observed=True)
        .agg(market_prob_mid=("market_prob_over", "mean"), actual_rate=("over_2_5", "mean"), n=("over_2_5", "count"))
        .reset_index(drop=True)
    )
    lines.append(f"{len(market)} matches have de-margined Avg odds coverage "
                  f"(2019/20 onward, per `data_dictionary.md`).\n")
    lines.append(md_table(calib) + "\n")

    fig, ax = plt.subplots(figsize=(6, 6))
    ax.plot([0, 1], [0, 1], "k--", label="perfect calibration")
    ax.scatter(calib["market_prob_mid"], calib["actual_rate"], s=calib["n"] / 20, alpha=0.7)
    ax.set_xlabel("Market-implied probability (de-margined)")
    ax.set_ylabel("Actual Over 2.5 rate")
    ax.set_title("Market calibration - de-margined odds vs outcome")
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(FIG_DIR, "market_calibration.png"), dpi=120)
    plt.close(fig)
    lines.append("![Market calibration](figures/market_calibration.png)\n")
    lines.append("This is Phase 7's Baseline C made visible: if the market is well "
                  "calibrated (points sit close to the diagonal), that's the real bar "
                  "the model needs to clear - not 50%, and not the raw league rate.\n")

    with open(REPORT_MD, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Wrote report to {REPORT_MD}")
    print(f"Wrote {3} figures to {FIG_DIR}")
    print(f"\nOverall Over 2.5 rate: {overall_rate:.1%}")
    print(f"Shots-goals corr: {shots_goals_corr:.3f}, SOT-goals corr: {sot_goals_corr:.3f}")
    print(f"Weak features (|corr|<0.03): {len(weak)} / {len(target_corr)}")
    print(f"Redundant feature pairs (|corr|>{REDUNDANCY_THRESHOLD}): {len(pairs)}")


if __name__ == "__main__":
    main()
